"""Step 5: build the paper (paper/manuscript.pdf) from paper/stats.json.

Plain-language note: the paper's text lives in paper/manuscript.tex, a LaTeX file
laid out as a two-column journal article. It never contains a typed-in result.
Instead, this script writes every number into paper/numbers.tex and the tables into
paper/tab_*.tex, then runs LaTeX to produce paper/manuscript.pdf. Run with --final
after verification to remove the DRAFT marking. You do not need to open this file.
"""
import json
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
S = json.loads((PAPER / "stats.json").read_text())
A = json.loads((ROOT / "AUTHORS.json").read_text())["authors"][0]
FINAL = "--final" in sys.argv

fl, lm, ps, bal = S["flow"], S["lm"], S["pass"], S["balance"]
sub = {r["group"]: r for r in S["subgroups"]}
f1 = lambda x: f"{x:.1f}"
f2 = lambda x: f"{x:.2f}"
pc = lambda x: f"{100 * x:.1f}\\%"
pp = lambda x: f"{100 * x:.1f}"
num = lambda x: f"{x:,}".replace(",", "{,}")


def minus(t):
    """Typeset negative numbers with a true minus sign."""
    import re
    return re.sub(r"(?<=[ \[(])-(?=\d)", "$-$", t)


def pv(p):
    return "$p < .001$" if p < 0.001 else f"$p = {p:.3f}$".replace("0.", ".", 1)


macros = {
    "Nrand": num(fl["randomized"]), "Nact": num(fl["randomized_active"]), "Nlec": num(fl["randomized_lecture"]),
    "Nstay": num(fl["stayers"]), "NstayAct": num(fl["stayed_active"]), "NstayLec": num(fl["stayed_lecture"]),
    "Nleft": num(fl["randomized"] - fl["stayers"]),
    "StayRateAct": pc(fl["stay_rate_active"]), "StayRateLec": pc(fl["stay_rate_lecture"]), "StayP": pv(S["stay_effect"]["p"]),
    "Nsections": str(fl["sections"]), "Nslots": str(fl["slots"]), "Ninstr": str(fl["instructors"]),
    "NinstrAct": str(fl["instructors_active"]), "NinstrLec": str(fl["instructors_lecture"]),
    "Nclusters": str(lm["fe"]["clusters"]), "Ndf": str(lm["fe"]["clusters"] - 1),
    "LMnAct": num(fl["lm_n_active"]), "LMnLec": num(fl["lm_n_lecture"]),
    "LMmeanAct": f1(lm["mean_active"]), "LMmeanLec": f1(lm["mean_lecture"]),
    "LMsdAct": f1(lm["sd_active"]), "LMsdLec": f1(lm["sd_lecture"]),
    "LMest": f1(lm["fe"]["est"]), "LMlo": f1(lm["fe"]["lo"]), "LMhi": f1(lm["fe"]["hi"]), "LMp": pv(lm["fe"]["p"]),
    "LMadj": f1(lm["fe_adj"]["est"]), "LMadjLo": f1(lm["fe_adj"]["lo"]), "LMadjHi": f1(lm["fe_adj"]["hi"]),
    "Gval": f2(lm["g"]["g"]), "Glo": f2(lm["g"]["lo"]), "Ghi": f2(lm["g"]["hi"]),
    "PairsFav": str(lm["pairs"]["pairs_favoring_active"]), "PairsN": str(lm["pairs"]["pairs"]),
    "PairsMean": f1(lm["pairs"]["mean_diff"]), "PairsPexact": pv(lm["pairs"]["p_exact"]),
    "PairsPt": pv(lm["pairs"]["p_paired_t"]),
    "LeeLo": f1(lm["lee"]["lower"]), "LeeHi": f1(lm["lee"]["upper"]),
    "LeeGlo": f2(lm["lee"]["lower_g"]), "LeeGhi": f2(lm["lee"]["upper_g"]), "LeeTrim": pc(lm["lee"]["trim_share"]),
    "MissAct": pc(1 - lm["lee"]["observed_share_active"]), "MissLec": pc(1 - lm["lee"]["observed_share_lecture"]),
    "PassAct": pc(ps["rate_active"]), "PassLec": pc(ps["rate_lecture"]),
    "PassEst": pp(ps["fe"]["est"]), "PassLo": pp(ps["fe"]["lo"]), "PassHi": pp(ps["fe"]["hi"]), "PassP": pv(ps["fe"]["p"]),
    "PassAdj": pp(ps["fe_adj"]["est"]), "PassAdjLo": pp(ps["fe_adj"]["lo"]), "PassAdjHi": pp(ps["fe_adj"]["hi"]),
    "PassPairsFav": str(ps["pairs"]["pairs_favoring_active"]), "PassPairsMean": pp(ps["pairs"]["mean_diff"]),
    "PassPairsPexact": pv(ps["pairs"]["p_exact"]),
    "DFWAct": pc(ps["dfw_active"]), "DFWLec": pc(ps["dfw_lecture"]), "DFWRed": pc(ps["relative_dfw_reduction"]),
    "PerHundred": str(round(100 * ps["fe"]["est"])),
    "PrepAct": f1(bal["prior_prep_mean_active"]), "PrepLec": f1(bal["prior_prep_mean_lecture"]), "PrepP": pv(bal["prior_prep_p"]),
    "PrepNoScoreLec": f1(bal["stayers_without_score_prior_prep_lecture"]),
    "PrepScoreLec": f1(bal["stayers_with_score_prior_prep_lecture"]),
    "SubLMmin": f1(min(r["lm"]["est"] for r in S["subgroups"])),
    "SubLMmax": f1(max(r["lm"]["est"] for r in S["subgroups"])),
    "SubPassHisp": pp(sub["Hispanic or Latino/a"]["pass"]["est"]),
    "SubPassTransfer": pp(sub["Transfer or other"]["pass"]["est"]),
    "BlackPassAct": pc(sub["Black or African American"]["pass_active"]),
    "BlackPassLec": pc(sub["Black or African American"]["pass_lecture"]),
    "Nblack": num(sub["Black or African American"]["n"]),
    "MinInterP": f"{min(v[k]['p'] for v in S['interactions'].values() for k in ('lm', 'pass')):.2f}",
    "ShareHisp": pc(S["sample"]["share_hispanic"]),
    "AuthorName": A["name"], "AuthorOrcid": A["orcid"], "AuthorEmail": A["email"],
    "AuthorAffil": A["affiliation"], "RepoURL": f"https://github.com/{A['github']}/calculus-active-learning",
}
lines = ["% Generated by code/05_manuscript.py from paper/stats.json. Do not edit by hand."]
for k, v in macros.items():
    lines.append(f"\\newcommand{{\\{k}}}{{{v}}}")
lines.append("\\newif\\ifdraftcopy\\draftcopy" + ("false" if FINAL else "true"))
(PAPER / "numbers.tex").write_text("\n".join(lines) + "\n")

# Table 1: main results
ci = lambda e, s=1: f"{f1(s * e['est'])} [{f1(s * e['lo'])}, {f1(s * e['hi'])}]"
t1 = rf"""\begin{{table*}}[t]
\centering
\caption{{Outcomes and estimated effects of active learning}}
\label{{tab:main}}
\begin{{tabular}}{{lccl}}
\toprule
Outcome & Active learning & Lecture & Estimated effect [95\% CI] \\
\midrule
Students in assigned section at drop/add & {fl['stayed_active']} & {fl['stayed_lecture']} & \nodata \\
Learning measure, mean (SD) & {f1(lm['mean_active'])} ({f1(lm['sd_active'])}) & {f1(lm['mean_lecture'])} ({f1(lm['sd_lecture'])}) & \\
\quad Time-slot fixed effects & & & {ci(lm['fe'])} points \\
\quad Adding prior preparation & & & {ci(lm['fe_adj'])} points \\
\quad Hedges' $g$ & & & {f2(lm['g']['g'])} [{f2(lm['g']['lo'])}, {f2(lm['g']['hi'])}] \\
\quad Lee bounds for missing scores & & & {f1(lm['lee']['lower'])} to {f1(lm['lee']['upper'])} points \\
Passed with C or better & {pc(ps['rate_active'])} & {pc(ps['rate_lecture'])} & \\
\quad Time-slot fixed effects & & & {ci(ps['fe'], 100)} pp \\
\quad Adding prior preparation & & & {ci(ps['fe_adj'], 100)} pp \\
D, F, or withdrawal (DFW) & {pc(ps['dfw_active'])} & {pc(ps['dfw_lecture'])} & {pc(ps['relative_dfw_reduction'])} relative reduction \\
\bottomrule
\end{{tabular}}
\tablecomments{{Students who remained in their assigned section ($n = {fl['stayers']}$). Effects are from ordinary least squares with time-slot fixed effects and standard errors clustered by section ({lm['fe']['clusters']} clusters). pp = percentage points.}}
\end{{table*}}
"""
(PAPER / "tab_main.tex").write_text(minus(t1))

# Table 2 (appendix): subgroup estimates
rows = []
for r in S["subgroups"]:
    g = r["group"].replace("Prior preparation: ", "Prior preparation, ")
    rows.append(f"{g} & {r['n']} & {ci(r['lm'])} & {pc(r['pass_active'])} & {pc(r['pass_lecture'])} & {ci(r['pass'], 100)} \\\\")
t2 = r"""\begin{table}[h!]
\centering\small\setlength{\tabcolsep}{5pt}
\caption{Effects of active learning within student groups (exploratory)}
\label{tab:subgroups}
\begin{tabular}{lccccc}
\toprule
Group & $n$ & Learning gain & Pass rate, & Pass rate, & Pass-rate gain, \\
 & & points [95\% CI] & active & lecture & pp [95\% CI] \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\tablecomments{Estimates from ordinary least squares with time-slot fixed effects within each group; confidence intervals clustered by section. Groups overlap and are not mutually exclusive.}
\end{table}
"""
(PAPER / "tab_subgroups.tex").write_text(minus(t2))

# Table 3 (appendix): section pairs
pr = []
pas = {d["slot"]: d for d in ps["pairs"]["by_slot"]}
for d in lm["pairs"]["by_slot"]:
    q = pas[d["slot"]]
    pr.append(f"{d['slot']} & {d['n_active']} & {d['n_lecture']} & {f1(d['mean_active'])} & {f1(d['mean_lecture'])} & "
              f"{d['mean_active'] - d['mean_lecture']:+.1f} & {pc(q['mean_active'])} & {pc(q['mean_lecture'])} \\\\")
t3 = r"""\begin{table}[h!]
\centering\small\setlength{\tabcolsep}{5pt}
\caption{Section-level comparison within each registration time slot}
\label{tab:pairs}
\begin{tabular}{cccccccc}
\toprule
& \multicolumn{2}{c}{$n$ with score} & \multicolumn{2}{c}{Mean learning score} & & \multicolumn{2}{c}{Pass rate} \\
\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){7-8}
Slot & Active & Lecture & Active & Lecture & Difference & Active & Lecture \\
\midrule
""" + "\n".join(pr) + r"""
\bottomrule
\end{tabular}
\tablecomments{Each slot contained one active-learning section and one lecture section. Score columns use students with a learning measure; pass columns use all students who remained in the section.}
\end{table}
"""
(PAPER / "tab_pairs.tex").write_text(minus(t3))

# Compile
for _ in range(2):
    r = subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "manuscript.tex"],
                       cwd=PAPER, capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout[-3000:])
        sys.exit("LaTeX failed")
for ext in ("aux", "log", "out"):
    (PAPER / f"manuscript.{ext}").unlink(missing_ok=True)
print("wrote paper/manuscript.pdf", "(final)" if FINAL else "(DRAFT)")
